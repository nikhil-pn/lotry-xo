// Builds docs/PROOF.md and web/data/rounds.json from rounds/*: every on-chain step with its transaction,
// and every invitation file. Run after any step: node scripts/export-proof.mjs
import fs from 'node:fs';
import path from 'node:path';
import { readRound, readSteps, txLink } from './lib-round.mjs';

const REPOSITORY = 'https://github.com/nikhil-pn/lotry-xo';
const blobLink = (file) => `${REPOSITORY}/blob/main/${file}`;

const STEP_TITLES = {
    open: 'Round opened',
    buy: 'Ticket sold',
    draw: 'Winner drawn',
    claim: 'Pot claimed',
    refund: 'Ticket refunded',
};

const who = (wallet) => wallet.replace(/^buyer_(\w)$/, (match, letter) => `buyer ${letter.toUpperCase()}`);

const describe = (step) => {
    switch (step.step) {
        case 'open': return 'Organiser creates the pot: token genesis, minting NFT, commitment = 0 tickets';
        case 'buy': return `Ticket #${step.ticketNumber} to ${who(step.buyer)} (two-party invitation: organiser adds the pot, player adds coins + ticket)`;
        case 'draw': return `Secret revealed; the covenant picks ticket #${step.winningTicket} of ${step.tickets} (pot ${step.potSatoshis} sats)`;
        case 'claim': return `The winner (${who(step.winner)}) spends the pot with winning ticket #${step.ticketNumber}; both NFTs burned`;
        case 'refund': return `Ticket #${step.ticketNumber} burned, price paid back to ${who(step.holder)}`;
        default: return step.step;
    }
};

const roundIds = fs.readdirSync('rounds').filter((name) => fs.existsSync(path.join('rounds', name, 'round.json'))).sort();
const rounds = roundIds.map((roundId) => {
    const round = readRound(roundId);
    const steps = readSteps(roundId).map((step) => ({ ...step, title: STEP_TITLES[step.step], description: describe(step), link: txLink(step.transactionHash) }));
    const invitations = fs.readdirSync(path.join('rounds', roundId, 'invitations')).sort()
        .map((name) => ({ name: name.replace('.json', ''), url: blobLink(`rounds/${roundId}/invitations/${name}`), raw: `${REPOSITORY.replace('github.com', 'raw.githubusercontent.com')}/main/rounds/${roundId}/invitations/${name}` }));
    const sold = steps.filter((step) => step.step === 'buy').length;
    const draw = steps.find((step) => step.step === 'draw');
    const claim = steps.find((step) => step.step === 'claim');
    const refunds = steps.filter((step) => step.step === 'refund').length;
    let status = `open, ${sold} tickets sold`;
    if (draw) status = `drawn: ticket #${draw.winningTicket} won`;
    if (claim) status = `finished: ticket #${claim.ticketNumber} claimed the pot`;
    if (refunds > 0 && !draw) status = `undrawn: ${refunds} of ${sold} tickets refunded`;
    return { ...round, status, ticketsSold: sold, steps, invitations };
});

fs.mkdirSync('web/data', { recursive: true });
fs.writeFileSync('web/data/rounds.json', `${JSON.stringify({ generatedAt: new Date().toISOString(), repository: REPOSITORY, rounds }, null, 2)}\n`);

const lines = [
    '# Proof: Lotry on XO, live on Chipnet',
    '',
    'Every row is a real Chipnet transaction made from an XO invitation built with the Lotry template',
    '(`src/lotry-template.mjs`). The invitation files are committed next to each round, so each step can be',
    'replayed in the XO debug tool (https://blaze.xo.cash). Generated by `node scripts/export-proof.mjs`.',
    '',
];
for (const round of rounds) {
    lines.push(`## ${round.roundId}: ${round.status}`, '');
    lines.push(`- Token category (the round): \`${round.roundCategory}\``);
    lines.push(`- Ticket price ${round.ticketPrice} sats · draw from lock height ${round.drawHeight} · refunds from lock height ${round.refundHeight}`);
    lines.push(`- Secret hash \`${round.secretHash}\``);
    if (round.roundId === 'round-20261121T1936') {
        lines.push('- ⚠️ Opened before we noticed Chipnet\'s Faster Blocks lock-time rule (see README): its draw height was set as a block height,',
            '  which is a lock height about 57 days away, so this round stays open as proof of the open and ticket steps.');
    }
    lines.push('', '| # | Step | What happened | Transaction |', '|---|---|---|---|');
    round.steps.forEach((step, index) => {
        lines.push(`| ${index + 1} | ${step.title} | ${step.description} | [${step.transactionHash.slice(0, 10)}…](${step.link}) |`);
    });
    lines.push('', 'Invitations: ' + round.invitations.map((invitation) => `[${invitation.name}](${invitation.url})`).join(' · '), '');
}
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/PROOF.md', `${lines.join('\n')}\n`);
console.log(`Wrote docs/PROOF.md and web/data/rounds.json for ${rounds.length} rounds`);
